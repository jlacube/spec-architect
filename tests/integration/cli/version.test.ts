// C002-TC-517 / C002-TS-517 and C002-TC-518 / C002-TS-518 (C002-AC-511.1, C002-REQ-511): `sdd --version`
// prints the bare version of plugin.json, `sdd version` keeps `architect-plugin@<semver>`. Plus the
// single-version-source consequences of C002-ADR-004: the `#!` first line of the bundle and PLG-VER-001.
// The installed-tarball row of TS-517 needs fx-tgz (C002-T-022); here the bundled CLI row runs.
import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { ver001 } from "../../../scripts/check/rules.mjs";
import { context } from "../../../scripts/check/lib.mjs";
import { repoRoot } from "../../helpers.ts";
import { CLI, runBundled, runInProcess } from "./helpers.ts";

const root = repoRoot();
const version = (JSON.parse(readFileSync(join(root, "plugins", "architect", ".claude-plugin", "plugin.json"), "utf8")) as { version: string }).version;

test("C002-TS-517: node plugins/architect/scripts/sdd.mjs --version prints exactly the bare version", () => {
  assert.match(version, /^\d+\.\d+\.\d+$/);
  const r = runBundled(["--version"], { cwd: tmpdir() });
  assert.deepEqual(r, { code: 0, stdout: `${version}\n`, stderr: "" });
});

test("C002-TS-517: --version needs no workspace and prints one line in-process", () => {
  const r = runInProcess(["--version"], { cwd: tmpdir() });
  assert.equal(r.code, 0);
  assert.equal(r.stderr, "");
  assert.equal(r.stdout.split("\n").filter(Boolean).length, 1);
});

test("C002-TS-518: sdd version keeps architect-plugin@<semver>", () => {
  const r = runBundled(["version"], { cwd: tmpdir() });
  assert.deepEqual(r, { code: 0, stdout: `architect-plugin@${version}\n`, stderr: "" });
});

test("the bundle starts with a #!/usr/bin/env node line, then the banner", () => {
  const [first, second] = readFileSync(CLI, "utf8").split("\n");
  assert.equal(first, "#!/usr/bin/env node");
  assert.equal(second, `// architect-plugin@${version} — sdd CLI. Generated by scripts/build.mjs; do not edit.`);
});

function repoWith(pkg: string | null, manifest: string): { ctx: ReturnType<typeof context>; cleanup: () => void } {
  const repo = realpathSync.native(mkdtempSync(join(tmpdir(), "sdd-ver-")));
  mkdirSync(join(repo, "plugins", "architect", ".claude-plugin"), { recursive: true });
  writeFileSync(join(repo, "plugins", "architect", ".claude-plugin", "plugin.json"), manifest);
  if (pkg !== null) writeFileSync(join(repo, "package.json"), pkg);
  return { ctx: context({ repo }), cleanup: () => rmSync(repo, { recursive: true, force: true }) };
}

test("PLG-VER-001: equal versions pass", () => {
  const { ctx, cleanup } = repoWith('{"version":"0.3.0"}', '{"version":"0.3.0"}');
  try {
    assert.deepEqual(ver001.check(ctx), []);
  } finally {
    cleanup();
  }
});

test("PLG-VER-001: a root package.json version that differs from plugin.json is an error naming both", () => {
  const { ctx, cleanup } = repoWith('{"version":"0.2.9"}', '{"version":"0.3.0"}');
  try {
    const f = ver001.check(ctx);
    assert.equal(f.length, 1);
    assert.equal(f[0]!.code, "PLG-VER-001");
    assert.equal(f[0]!.path, "package.json");
    assert.match(f[0]!.message, /0\.2\.9.*0\.3\.0/);
  } finally {
    cleanup();
  }
});

test("PLG-VER-001: a missing root package.json or plugin.json version is reported", () => {
  for (const [pkg, manifest] of [[null, '{"version":"0.3.0"}'], ['{"version":"0.3.0"}', "{}"]] as const) {
    const { ctx, cleanup } = repoWith(pkg, manifest);
    try {
      assert.equal(ver001.check(ctx).length, 1, `${pkg} / ${manifest}`);
    } finally {
      cleanup();
    }
  }
});

test("PLG-VER-001: the repository's own versions agree", () => {
  assert.deepEqual(ver001.check(context({ repo: root })), []);
});
