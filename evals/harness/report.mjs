// Aggregates evals/results/*.json into docs/metrics/eval-metrics.md (C001-ADR-003): per scenario,
// per agent and per tier label, mean / p50 / p95 / max of cost, tokens and duration, and a
// release-tier projection (10 runs × scenarios × p95). Usage: node evals/harness/report.mjs
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT } from "./fixtures.mjs";

const RESULTS = join(ROOT, "evals", "results");
const OUT = join(ROOT, "docs", "metrics", "eval-metrics.md");

export function stats(values) {
  const v = values.filter((x) => typeof x === "number" && Number.isFinite(x)).sort((a, b) => a - b);
  if (v.length === 0) return { n: 0, mean: null, p50: null, p95: null, max: null };
  const at = (q) => v[Math.min(v.length - 1, Math.max(0, Math.ceil(q * v.length) - 1))];
  return { n: v.length, mean: v.reduce((a, b) => a + b, 0) / v.length, p50: at(0.5), p95: at(0.95), max: v[v.length - 1] };
}

const tokensOf = (t) => (t?.input ?? 0) + (t?.output ?? 0) + (t?.cache_read ?? 0) + (t?.cache_write ?? 0);
const usd = (x) => (x === null ? "—" : `$${x.toFixed(4)}`);
const sec = (x) => (x === null ? "—" : `${(x / 1000).toFixed(1)} s`);
const int = (x) => (x === null ? "—" : Math.round(x).toLocaleString("en-US"));

/** Loads every result document (records of the SDK harness and of `claude plugin eval` runs). */
export function loadResults(dir = RESULTS) {
  let files = [];
  try {
    files = readdirSync(dir).filter((f) => f.endsWith(".json"));
  } catch {
    return [];
  }
  return files.map((f) => JSON.parse(readFileSync(join(dir, f), "utf8"))).filter((d) => Array.isArray(d.records));
}

export function renderReport(docs, now = new Date()) {
  const runs = docs.flatMap((d) => d.records.map((r) => ({ scenario: d.scenario, label: d.label, pass: r.pass, m: r.metrics })));
  const lines = [
    "# Eval metrics",
    "",
    `Generated by \`node evals/harness/report.mjs\` from \`evals/results/\` on ${now.toISOString().slice(0, 10)}`,
    `(${docs.length} result files, ${runs.length} runs). Costs are list-price estimates from Claude Code.`,
    "Tiers and pass rules: C001-ADR-003.",
    "",
    "## Per scenario",
    "",
    "| Scenario | Runs | Passed | Cost mean | Cost p95 | Tokens p50 | Tokens p95 | Duration p50 | Duration p95 | Duration max |",
    "|---|---|---|---|---|---|---|---|---|---|",
  ];
  const scenarios = [...new Set(runs.map((r) => r.scenario))].sort();
  const p95ByScenario = {};
  for (const s of scenarios) {
    const rs = runs.filter((r) => r.scenario === s);
    const cost = stats(rs.map((r) => r.m.cost_usd));
    const tok = stats(rs.map((r) => Object.values(r.m.tokens_by_model ?? {}).reduce((a, t) => a + tokensOf(t), 0)));
    const dur = stats(rs.map((r) => r.m.session_ms));
    p95ByScenario[s] = { cost: cost.p95 ?? 0, dur: dur.p95 ?? 0 };
    lines.push(`| ${s} | ${rs.length} | ${rs.filter((r) => r.pass).length} | ${usd(cost.mean)} | ${usd(cost.p95)} | ${int(tok.p50)} | ${int(tok.p95)} | ${sec(dur.p50)} | ${sec(dur.p95)} | ${sec(dur.max)} |`);
  }

  lines.push("", "## Per agent", "", "| Agent | Models | Runs | Input p50 | Output p50 | Cache read p50 | Cache write p50 | Tokens p95 |", "|---|---|---|---|---|---|---|---|");
  const agents = {};
  for (const r of runs) for (const [a, e] of Object.entries(r.m.tokens_by_agent ?? {})) (agents[a] ??= { models: new Set(), rows: [] }).rows.push(e.tokens), e.models.forEach((m) => agents[a].models.add(m));
  for (const [a, { models, rows }] of Object.entries(agents).sort())
    lines.push(`| ${a} | ${[...models].join(", ")} | ${rows.length} | ${int(stats(rows.map((t) => t.input)).p50)} | ${int(stats(rows.map((t) => t.output)).p50)} | ${int(stats(rows.map((t) => t.cache_read)).p50)} | ${int(stats(rows.map((t) => t.cache_write)).p50)} | ${int(stats(rows.map(tokensOf)).p95)} |`);

  lines.push("", "## Subagents and tool calls", "", "| Kind | Name | Count | Duration p50 | Duration p95 | Duration max |", "|---|---|---|---|---|---|");
  const subs = {};
  for (const r of runs) for (const s of r.m.subagents ?? []) (subs[s.subagent] ??= []).push(s.ms);
  for (const [n, ms] of Object.entries(subs).sort()) {
    const st = stats(ms);
    lines.push(`| subagent | ${n} | ${ms.length} | ${sec(st.p50)} | ${sec(st.p95)} | ${sec(st.max)} |`);
  }
  const tools = {};
  for (const r of runs) for (const t of r.m.tool_timings ?? []) (tools[t.tool] ??= []).push(t.ms);
  for (const [n, ms] of Object.entries(tools).sort()) {
    const st = stats(ms);
    lines.push(`| tool | ${n} | ${ms.length} | ${sec(st.p50)} | ${sec(st.p95)} | ${sec(st.max)} |`);
  }

  lines.push("", "## Per tier label", "", "| Label | Result files | Runs | Passed | Cost total |", "|---|---|---|---|---|");
  for (const label of [...new Set(docs.map((d) => d.label))].sort()) {
    const ds = docs.filter((d) => d.label === label);
    const rs = ds.flatMap((d) => d.records);
    lines.push(`| ${label} | ${ds.length} | ${rs.length} | ${rs.filter((r) => r.pass).length} | ${usd(rs.reduce((a, r) => a + (r.metrics.cost_usd ?? 0), 0))} |`);
  }

  const n = scenarios.length;
  const projCost = Object.values(p95ByScenario).reduce((a, s) => a + 10 * s.cost, 0);
  const projDur = Object.values(p95ByScenario).reduce((a, s) => a + 10 * s.dur, 0);
  lines.push(
    "",
    "## Release-tier projection",
    "",
    `10 runs × ${n} scenario${n === 1 ? "" : "s"} measured so far × p95 per scenario: cost ${usd(projCost)}, sequential duration ${sec(projDur)}.`,
    "The release tier covers every eval-level test case of the test plan; scale by the number of",
    "scenarios when more evals are measured.",
    "",
  );
  return lines.join("\n");
}

// Script entry only (bundled into a test, import.meta.filename is the test file).
if (process.argv[1]?.endsWith("report.mjs") && import.meta.filename === process.argv[1]) {
  const docs = loadResults();
  mkdirSync(join(ROOT, "docs", "metrics"), { recursive: true });
  writeFileSync(OUT, renderReport(docs));
  console.log(`written: docs/metrics/eval-metrics.md (${docs.length} result files)`);
}
