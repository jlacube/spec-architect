// Machine configurations for code-intelligence scenarios (C001-T-041; tests/fixtures/cfg-README.md):
// each gives the session a PATH and a plugin overlay. ripwire is the real 0.6.5 install from spike
// S-01 (not on the user PATH), prepended only for the configurations that have it.
//
// The Bash tool of a session rebuilds PATH from the user's shell profile, so the PATH of the child
// process alone does not reach it: each configuration also writes a shell file that Claude Code sources
// before every Bash command (CLAUDE_ENV_FILE) and that applies the same drops and prepends.
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { delimiter, join } from "node:path";
import { ROOT } from "./fixtures.mjs";
import { architectWithStubs, architectWithout, architectWithUrls } from "./overlay.mjs";

export const RIPWIRE_DIR = join(homedir(), ".local", "ripwire", "bin", "ripwire-0.6.5-windows-x64");
const SHIMS = (name) => join(ROOT, "tests", "fixtures", name, "bin");

const pathKey = () => Object.keys(process.env).find((k) => k.toUpperCase() === "PATH") ?? "PATH";

/** `C:\a\b` → `/c/a/b` (Git Bash). */
const posix = (p) => p.replace(/^([A-Za-z]):[\\/]/, (_, d) => `/${d.toLowerCase()}/`).split("\\").join("/");

// Each drop: a JS test for Windows PATH entries and an ERE for Git Bash PATH entries.
const NO_RIPWIRE = [{ js: /ripwire/i, ere: "ripwire" }];
const NO_AST_GREP = [{ js: /Python\d*[\\/]Scripts/i, ere: "Python[0-9]*/Scripts" }, { js: /ast-grep/i, ere: "ast-grep" }];
// Serena and other uv tools live in ~/.local/bin: cfg-bare has no Serena at all (C001-TS-121).
const NO_UV_TOOLS = [{ js: /[\\/]\.local[\\/]bin$/i, ere: "/\\.local/bin$" }];

const CSC = join(process.env.SystemRoot ?? "C:\\Windows", "Microsoft.NET", "Framework64", "v4.0.30319", "csc.exe");

/**
 * Windows only: the folder of the native `node.exe` version shim of cfg-node18
 * (tests/fixtures/cfg-node18/node-shim.cs), compiled once per source hash into the temporary folder. The
 * sdd MCP server's command tool runs native executables only (C002-IF-002 §5.2), so the `sh` shim
 * `bin/node` alone never answers an OpenCode doctor probe (C002-TC-509 row node18). Elsewhere: none.
 */
function nativeNodeShim() {
  if (process.platform !== "win32") return [];
  const src = join(ROOT, "tests", "fixtures", "cfg-node18", "node-shim.cs");
  const hash = createHash("sha256").update(readFileSync(src)).digest("hex").slice(0, 10);
  const dir = join(tmpdir(), "sdd-eval-shims", `cfg-node18-native-${hash}`);
  const exe = join(dir, "node.exe");
  if (!existsSync(exe)) {
    if (!existsSync(CSC)) throw new Error(`cfg-node18 needs the .NET Framework compiler at ${CSC} for its native node.exe shim`);
    mkdirSync(dir, { recursive: true });
    const r = spawnSync(CSC, ["/nologo", "/target:exe", `/out:${exe}`, src], { encoding: "utf8", windowsHide: true });
    if (r.status !== 0 || !existsSync(exe)) throw new Error(`cfg-node18: compiling ${src} failed: ${(r.stdout ?? "") + (r.stderr ?? "") || r.error?.message}`);
  }
  return [dir];
}

/** ERE-escaped text (Git Bash PATH drops). */
const ere = (s) => s.replace(/[.[\]()*+?{}|^$\\]/g, "\\$&");
const reEscape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/**
 * Drops for every PATH entry that holds an executable named `tool` (`<tool>`, `.cmd`, `.exe`, `.ps1`,
 * `.bat`), so that no bare `<tool>` resolves in the session (C002-TC-509, "no sdd executable on PATH";
 * an `opencode missing` configuration, C002-TC-676).
 */
function noToolDrops(tool) {
  const names = new Set(["", ".cmd", ".exe", ".ps1", ".bat"].map((e) => tool + e));
  const dirs = String(process.env[pathKey()] ?? "")
    .split(delimiter)
    .filter((p) => {
      try {
        return p && readdirSync(p).some((n) => names.has(n.toLowerCase()));
      } catch {
        return false;
      }
    });
  return dirs.map((d) => ({ js: new RegExp(`^${reEscape(d.replace(/[\\/]+$/, ""))}[\\\\/]?$`, "i"), ere: `^${ere(posix(d))}/?$` }));
}

function withPath(cfg, { prepend = [], drop = [] } = {}) {
  const key = pathKey();
  const parts = String(process.env[key] ?? "").split(delimiter).filter((p) => p && !drop.some((d) => d.js.test(p)));
  const lines = ["# Generated by evals/harness/machines.mjs for " + cfg];
  if (drop.length > 0) lines.push(`PATH="$(printf '%s' "$PATH" | tr ':' '\\n' | grep -v -i -E '${drop.map((d) => d.ere).join("|")}' | paste -sd: -)"`);
  if (prepend.length > 0) lines.push(`PATH="${prepend.map(posix).join(":")}:$PATH"`);
  lines.push("export PATH", "");
  const envFile = join(tmpdir(), `sdd-eval-${cfg}.env.sh`);
  writeFileSync(envFile, lines.join("\n"));
  // Serena starts in a few seconds; the margin covers a cold start (MCP connect timeout, ms).
  return { [key]: [...prepend, ...parts].join(delimiter), CLAUDE_ENV_FILE: envFile, MCP_TIMEOUT: "60000" };
}

/**
 * `{ env, plugins }` for a configuration name. `prepend` adds folders (version shims of a case) before
 * the configuration's own PATH entries. `lead` (C002-IF-010 §4 PATH lead, defect D-020 item 4): folders
 * placed right after the case's `prepend` folders and before the configuration's own folders (the
 * folder of the pinned OpenCode binary on the OpenCode rows); the Git Bash env file applies the same
 * order. `without: ["opencode"]` removes every folder that holds an `opencode` executable and takes no
 * lead (an `opencode missing` configuration).
 */
export function machine(cfg, { prepend: extra = [], without = [], lead = [] } = {}) {
  const dropOf = { "ast-grep": () => NO_AST_GREP, opencode: () => noToolDrops("opencode") };
  for (const w of without) if (!dropOf[w]) throw new Error(`machine ${cfg}: cannot drop ${w}`);
  const extraDrops = without.flatMap((w) => dropOf[w]());
  const leads = without.includes("opencode") ? [] : lead;
  // A configuration with case shims, a lead or drops gets its own env file (one per variant, not per name).
  const variant = extra.length > 0 || without.length > 0 || leads.length > 0 ? `-${createHash("sha256").update(JSON.stringify([extra, without, leads])).digest("hex").slice(0, 10)}` : "";
  const withPathOf = (name, { prepend = [], drop = [] } = {}) => withPath(name + variant, { prepend: [...extra, ...leads, ...prepend], drop: [...drop, ...extraDrops] });
  switch (cfg) {
    case "cfg-full":
      if (!existsSync(join(RIPWIRE_DIR, "ripwire.exe"))) throw new Error(`cfg-full needs ripwire at ${RIPWIRE_DIR}`);
      return { env: withPathOf(cfg, { prepend: [RIPWIRE_DIR], drop: NO_RIPWIRE }), plugins: [architectWithStubs] };
    case "cfg-no-ripwire":
      return { env: withPathOf(cfg, { drop: NO_RIPWIRE }), plugins: [architectWithStubs] };
    case "cfg-bare":
      return { env: withPathOf(cfg, { drop: [...NO_RIPWIRE, ...NO_AST_GREP, ...NO_UV_TOOLS] }), plugins: [architectWithout("serena")] };
    case "cfg-ripwire-crash":
      return { env: withPathOf(cfg, { prepend: [SHIMS("cfg-ripwire-crash")], drop: NO_RIPWIRE }), plugins: [architectWithStubs] };
    case "cfg-ripwire-exit4":
      return { env: { ...withPathOf(cfg, { prepend: [SHIMS("cfg-ripwire-exit4")], drop: NO_RIPWIRE }), RIPWIRE_REAL: RIPWIRE_DIR }, plugins: [architectWithStubs] };
    case "cfg-claude-min":
      if (!existsSync(join(RIPWIRE_DIR, "ripwire.exe"))) throw new Error(`cfg-claude-min needs ripwire at ${RIPWIRE_DIR}`);
      return { env: withPathOf(cfg, { prepend: [RIPWIRE_DIR, SHIMS("cfg-claude-min")], drop: NO_RIPWIRE }), plugins: [architectWithStubs] };
    case "cfg-no-sdd":
      if (!existsSync(join(RIPWIRE_DIR, "ripwire.exe"))) throw new Error(`cfg-no-sdd needs ripwire at ${RIPWIRE_DIR}`);
      return { env: withPathOf(cfg, { prepend: [RIPWIRE_DIR], drop: [...NO_RIPWIRE, ...noToolDrops("sdd")] }), plugins: [architectWithStubs] };
    case "cfg-old-claude":
      return { env: withPathOf(cfg, { prepend: [SHIMS("cfg-old-claude")], drop: NO_RIPWIRE }), plugins: [architectWithStubs] };
    case "cfg-node18":
      return { env: { ...withPathOf(cfg, { prepend: [SHIMS("cfg-node18"), ...nativeNodeShim()], drop: NO_RIPWIRE }), NODE_REAL: process.execPath }, plugins: [architectWithStubs] };
    case "cfg-deepwiki-down":
      return { env: withPathOf(cfg, { drop: NO_RIPWIRE }), plugins: [architectWithUrls({ deepwiki: "https://deepwiki-unreachable.invalid/mcp" })] };
    default:
      throw new Error(`unknown machine configuration ${cfg}`);
  }
}
