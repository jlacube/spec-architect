// Bundled-dependency licenses (C001-REQ-1113, C001-REQ-1114): from the esbuild metafile, the packages
// bundled into scripts/sdd.mjs with version and license; the build fails on a license outside the
// allowlist and regenerates the "Bundled" section of plugins/architect/THIRD_PARTY_NOTICES.md.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const ALLOWED = ["MIT", "ISC", "BSD-2-Clause", "BSD-3-Clause", "Apache-2.0", "0BSD"];
const BEGIN = "<!-- bundled:begin (generated by scripts/build.mjs) -->";
const END = "<!-- bundled:end -->";

/** Packages whose files are inputs of the bundle: [{ name, version, license, dir }], sorted by name. */
export function bundledPackages(root, metafile) {
  const found = new Map();
  for (const input of Object.keys(metafile.inputs)) {
    const m = /(?:^|\/)node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input.split("\\").join("/"));
    if (!m || found.has(m[1])) continue;
    const dir = join(root, "node_modules", ...m[1].split("/"));
    const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    const license = typeof pkg.license === "string" ? pkg.license : (pkg.license?.type ?? "UNKNOWN");
    found.set(m[1], { name: m[1], version: pkg.version, license, dir });
  }
  return [...found.values()].sort((a, b) => a.name.localeCompare(b.name));
}

/** Packages whose license is outside the allowlist (an SPDX `OR` expression passes when one side does). */
export function disallowed(pkgs) {
  return pkgs.filter((p) => !p.license.replace(/[()]/g, "").split(/\s+OR\s+/).some((l) => ALLOWED.includes(l.trim())));
}

function licenseText(dir) {
  const f = existsSync(dir) ? readdirSync(dir).find((n) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(n)) : undefined;
  return f ? readFileSync(join(dir, f), "utf8").trim() : "(no license file in the package)";
}

export function renderBundled(pkgs) {
  const parts = pkgs.map((p) => [`### ${p.name} ${p.version} — ${p.license}`, "", "```text", licenseText(p.dir), "```"].join("\n"));
  return [BEGIN, "", ...(parts.length ? parts : ["None."]), "", END].join("\n");
}

/** Rewrites the bundled section of the notices file; returns true when the file changed. */
export function writeNotices(path, pkgs) {
  const text = readFileSync(path, "utf8");
  const a = text.indexOf(BEGIN);
  const b = text.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${path}: markers ${BEGIN} … ${END} not found`);
  const next = text.slice(0, a) + renderBundled(pkgs) + text.slice(b + END.length);
  if (next === text) return false;
  writeFileSync(path, next);
  return true;
}
