// Bundles src/cli.ts into the single shipped CLI file plugins/architect/scripts/sdd.mjs
// (C001-ADR-002, C001-CON-02): one ESM file, no runtime npm install.
import { build } from "esbuild";
import { readFileSync, readdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { bundledPackages, disallowed, writeNotices } from "./licenses.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const outdir = join(root, "plugins", "architect", "scripts");
const outfile = join(outdir, "sdd.mjs");

// The scripts folder must hold only the bundle.
for (const name of readdirSync(outdir)) {
  if (name !== "sdd.mjs") rmSync(join(outdir, name), { recursive: true, force: true });
}

const result = await build({
  entryPoints: [join(root, "src", "cli.ts")],
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  charset: "utf8",
  legalComments: "eof",
  define: { __SDD_VERSION__: JSON.stringify(version) },
  // Bundled CommonJS dependencies (yaml) call require() for Node built-ins; an ESM bundle has no
  // require, so provide one.
  banner: {
    js: [
      `// architect-plugin@${version} — sdd CLI. Generated by scripts/build.mjs; do not edit.`,
      `import { createRequire as __sddCreateRequire } from "node:module";`,
      `const require = __sddCreateRequire(import.meta.url);`,
    ].join("\n"),
  },
  logLevel: "warning",
  metafile: true,
});

// C001-REQ-1114: only permissive licenses may be bundled; C001-REQ-1113: the notices list them all.
const pkgs = bundledPackages(root, result.metafile);
const bad = disallowed(pkgs);
if (bad.length > 0) {
  console.error(`build failed: bundled package license not allowed: ${bad.map((p) => `${p.name}@${p.version} (${p.license})`).join(", ")}`);
  process.exit(1);
}
if (writeNotices(join(root, "plugins", "architect", "THIRD_PARTY_NOTICES.md"), pkgs)) console.log("updated plugins/architect/THIRD_PARTY_NOTICES.md");

console.log(`built ${outfile.slice(root.length + 1).replaceAll("\\", "/")} (architect-plugin@${version})`);
