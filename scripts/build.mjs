// Bundles src/cli.ts into the single shipped CLI file plugins/architect/scripts/sdd.mjs
// (C001-ADR-002, C001-CON-02): one ESM file, no runtime npm install.
import { build } from "esbuild";
import { readFileSync, readdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const outdir = join(root, "plugins", "architect", "scripts");
const outfile = join(outdir, "sdd.mjs");

// The scripts folder must hold only the bundle.
for (const name of readdirSync(outdir)) {
  if (name !== "sdd.mjs") rmSync(join(outdir, name), { recursive: true, force: true });
}

await build({
  entryPoints: [join(root, "src", "cli.ts")],
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  charset: "utf8",
  legalComments: "eof",
  define: { __SDD_VERSION__: JSON.stringify(version) },
  banner: { js: `// architect-plugin@${version} — sdd CLI. Generated by scripts/build.mjs; do not edit.` },
  logLevel: "warning",
});

console.log(`built ${outfile.slice(root.length + 1).replaceAll("\\", "/")} (architect-plugin@${version})`);
