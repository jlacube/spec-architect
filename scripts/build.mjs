// Bundles src/cli.ts into the single shipped CLI file plugins/architect/scripts/sdd.mjs
// (C001-ADR-002, C001-CON-02): one ESM file, no runtime npm install. In the same esbuild run,
// src/mcp/server.ts becomes build/npm/sdd-mcp.mjs, the sdd MCP server of architect-sdd (C002-ADR-004):
// outside the plugin, whose scripts folder holds only sdd.mjs (C002-CON-12). The licence check runs over
// both bundles (ERR-BLD-001, C002-REQ-413); the plugin's notices list sdd.mjs only, and
// build/npm/THIRD_PARTY_NOTICES.md lists the union for architect-sdd (C002-REQ-414).
import { build } from "esbuild";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { bundledPackages, licenseErrors, renderNotices, writeNotices } from "./licenses.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// C002-CON-16, C002-ADR-004: plugin.json is the single version source (the root package.json is not read).
const { version } = JSON.parse(readFileSync(join(root, "plugins", "architect", ".claude-plugin", "plugin.json"), "utf8"));
const outdir = join(root, "plugins", "architect", "scripts");
const npmdir = join(root, "build", "npm");
const rel = (p) => relative(root, p).split("\\").join("/");

/** The entries: bin name, source, output file and the banner's description. */
const ENTRIES = [
  { name: "sdd", entry: join(root, "src", "cli.ts"), outfile: join(outdir, "sdd.mjs"), what: "sdd CLI" },
  { name: "sdd-mcp", entry: join(root, "src", "mcp", "server.ts"), outfile: join(npmdir, "sdd-mcp.mjs"), what: "sdd MCP server" },
];

// The scripts folder must hold only the bundle.
for (const name of readdirSync(outdir)) {
  if (name !== "sdd.mjs") rmSync(join(outdir, name), { recursive: true, force: true });
}

const result = await build({
  entryPoints: ENTRIES.map((e) => ({ in: e.entry, out: e.name })),
  outdir: npmdir, // not written: each output goes to its own file below
  write: false,
  absWorkingDir: root, // metafile paths are relative to root
  outExtension: { ".js": ".mjs" },
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  charset: "utf8",
  legalComments: "eof",
  define: { __SDD_VERSION__: JSON.stringify(version) },
  // Bundled CommonJS dependencies (yaml, ajv) call require() for Node built-ins; an ESM bundle has no
  // require, so provide one.
  banner: {
    js: [`import { createRequire as __sddCreateRequire } from "node:module";`, `const require = __sddCreateRequire(import.meta.url);`].join("\n"),
  },
  logLevel: "warning",
  metafile: true,
});

// Per entry: its output text and the packages of its own inputs.
const built = ENTRIES.map((e) => {
  const out = join(npmdir, `${e.name}.mjs`);
  const file = result.outputFiles.find((f) => f.path === out);
  const meta = Object.entries(result.metafile.outputs).find(([p]) => join(root, p) === out)?.[1];
  if (!file || !meta) throw new Error(`build: no output for ${e.name}`);
  return { ...e, text: file.text, meta, pkgs: bundledPackages(root, meta) };
});

// C001-REQ-1114, C002-REQ-413 (ERR-BLD-001): only permissive licenses may be bundled into any entry.
const errors = licenseErrors(built);
if (errors.length > 0) {
  for (const line of errors) console.error(line);
  process.exit(1);
}

// The `#!` first line lets npm install each bundle as an executable (C002-ADR-004), then the banner.
for (const e of built) {
  mkdirSync(dirname(e.outfile), { recursive: true });
  writeFileSync(e.outfile, `#!/usr/bin/env node\n// architect-plugin@${version} — ${e.what}. Generated by scripts/build.mjs; do not edit.\n${e.text}`);
}

// C001-REQ-1113: the plugin's notices list what scripts/sdd.mjs bundles; C002-REQ-414: the union for architect-sdd.
const cli = built.find((e) => e.name === "sdd");
if (writeNotices(join(root, "plugins", "architect", "THIRD_PARTY_NOTICES.md"), cli.pkgs)) console.log("updated plugins/architect/THIRD_PARTY_NOTICES.md");
const union = bundledPackages(root, built.map((e) => e.meta));
writeFileSync(join(npmdir, "THIRD_PARTY_NOTICES.md"), renderNotices("`scripts/sdd.mjs` and `scripts/sdd-mcp.mjs`", union));

for (const e of built) console.log(`built ${rel(e.outfile)} (architect-plugin@${version})`);
