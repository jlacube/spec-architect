"""Prototype generator for 80-traceability.md and 85-open-items.md (precursor of `sdd trace --write`)."""
import re, os, glob, collections, sys

root = sys.argv[1]
NL = chr(10)
BS = chr(92)


def rd(p):
    return open(p, encoding='utf-8').read()


def field_ids(block, name, pat):
    m = re.search(r'- \*\*' + name + r':\*\* (.*)', block)
    return re.findall(pat, m.group(1)) if m else []


caps = sorted(glob.glob(os.path.join(root, '20-capabilities', 'CAP-*')))
fw, bw = [], []
stats = collections.Counter()
for c in caps:
    cap = os.path.basename(c)
    st, rq, ac = rd(c + '/stories.md'), rd(c + '/requirements.md'), rd(c + '/acceptance.md')
    us2req = {m.group(1): field_ids(m.group(0), 'Requirements', r'C001-REQ-\d+')
              for m in re.finditer(r'^### (C001-US-\d+).*?(?=^### |\Z)', st, re.S | re.M)}
    req2ac = {m.group(1): field_ids(m.group(0), 'Acceptance', r'C001-AC-\d+\.\d+')
              for m in re.finditer(r'^### (C001-REQ-\d+).*?(?=^### |\Z)', rq, re.S | re.M)}
    ac2ts = collections.defaultdict(list)
    cur = None
    for line in ac.split(NL):
        m = re.match(r'^#### (C001-AC-\d+\.\d+)', line)
        if m:
            cur = m.group(1)
        m = re.search(r'Scenario(?: Outline)?: (C001-TS-\d+)', line)
        if m and cur:
            ac2ts[cur].append(m.group(1))
    stats['US'] += len(us2req)
    stats['US_ok'] += sum(1 for v in us2req.values() if v)
    stats['REQ'] += len(req2ac)
    stats['REQ_ok'] += sum(1 for v in req2ac.values() if v)
    stats['AC'] += sum(len(v) for v in req2ac.values())
    stats['AC_ok'] += sum(1 for v in req2ac.values() for a in v if ac2ts.get(a))
    req2us = collections.defaultdict(list)
    for us, reqs in us2req.items():
        for r in reqs:
            req2us[r].append(us)
            for a in req2ac.get(r, []):
                fw.append((cap, us, r, a, ', '.join(ac2ts.get(a, []))))
    for r, acs in req2ac.items():
        for a in acs:
            for t in ac2ts.get(a, []):
                bw.append((t, a, r, ', '.join(sorted(set(req2us[r])))))

nfr = rd(os.path.join(root, '30-nfr', 'nfr.md'))
blocks = re.findall(r'^### C001-NFR-\d+.*?(?=^### |^## |\Z)', nfr, re.S | re.M)
nfrs = [re.match(r'### (C001-NFR-\d+)', b).group(1) for b in blocks]
nfr_ok = sum(1 for b in blocks if all(re.search(r'- \*\*' + f + r':\*\* \S', b) for f in ['Metric', 'Threshold', 'Method']))
dod = rd(os.path.join(root, '70-dod.md'))
dod_caps = set(re.findall(r'CAP-\d+', dod))
dod_nfr = set()
for line in dod.split(NL):
    if 'C001-NFR-' not in line:
        continue
    cell = line[line.index('C001-NFR-'):]
    for a, b in re.findall(r'(\d{3})(?:\s*…\s*(\d{3}))?', cell):
        rng = range(int(a), int(b) + 1) if b else [int(a)]
        dod_nfr |= {'C001-NFR-%03d' % n for n in rng}
nfr_dod = sum(1 for n in nfrs if n in dod_nfr)
req_dod = stats['REQ'] if len(dod_caps) >= len(caps) else 0


def pct(a, b):
    return '%d / %d (%d%%)' % (a, b, (100 * a // b) if b else 100)


out = ['---', 'artifact: spec/traceability', 'change: CHG-001', 'phase: 10-spec', 'generated: true', '---', '',
       '# C001 — Traceability (generated)', '',
       'Generated by the prototype trace generator (precursor of `sdd trace --write`); do not edit by hand.', '',
       '## Coverage', '', '| Rule | Coverage |', '|---|---|',
       '| TR-01 Every US lists ≥ 1 REQ | %s |' % pct(stats['US_ok'], stats['US']),
       '| TR-02 Every REQ has ≥ 1 AC | %s |' % pct(stats['REQ_ok'], stats['REQ']),
       '| TR-03 Every AC has ≥ 1 TS | %s |' % pct(stats['AC_ok'], stats['AC']),
       '| TR-04 Every NFR has metric, threshold, method | %s |' % pct(nfr_ok, len(nfrs)),
       '| TR-05 Every REQ covered by a DoD item (via capability rows) | %s |' % pct(req_dod, stats['REQ']),
       '| TR-05 Every NFR covered by a DoD item | %s |' % pct(nfr_dod, len(nfrs)), '',
       '## Forward: US → REQ → AC → TS', '', '| Capability | US | REQ | AC | TS |', '|---|---|---|---|---|']
out += ['| %s | %s | %s | %s | %s |' % row for row in fw]
out += ['', '## Backward: TS → AC → REQ → US', '', '| TS | AC | REQ | US |', '|---|---|---|---|']
out += ['| %s | %s | %s | %s |' % row for row in sorted(bw, key=lambda x: int(x[0].split('-')[-1]))]
open(os.path.join(root, '80-traceability.md'), 'w', encoding='utf-8', newline=NL).write(NL.join(out) + NL)

items = []
FENCE = chr(96) * 3
for p in sorted(glob.glob(os.path.join(root, '**', '*.md'), recursive=True)):
    rel = os.path.relpath(p, root).replace(os.sep, '/')
    if rel.startswith(('80-', '85-', '90-')):
        continue
    txt = re.sub(re.escape(FENCE) + r'.*?' + re.escape(FENCE), lambda m: NL * m.group(0).count(NL), rd(p), flags=re.S)
    for i, line in enumerate(txt.split(NL), 1):
        clean = re.sub(r'`[^`]*`', '', line)
        clean = re.sub(r'"[^"]*"', '', clean)
        for kind in ['NEEDS CLARIFICATION', 'ASSUMPTION', 'WAIVED', 'VERIFY']:
            if '[' + kind in clean:
                items.append((kind, rel, i, line.strip()[:140].replace('|', BS + '|')))
counts = collections.Counter(x[0] for x in items)
oi = ['---', 'artifact: spec/open-items', 'change: CHG-001', 'phase: 10-spec', 'generated: true', '---', '',
      '# C001 — Open items (generated)', '',
      'Markers are counted outside code spans, quoted strings and fenced blocks (C001-REQ-716). `[VERIFY]` items are claims about third-party tools to be confirmed by verification spikes S-01 … S-06 in the plan phase; they are not clarification markers and do not block G2.', '',
      'Total: %d (%s)' % (len(items), ', '.join('%s: %d' % kv for kv in counts.items()) or 'none'), '',
      '| Kind | File | Line | Text |', '|---|---|---|---|'] + ['| %s | %s | %d | %s |' % it for it in items]
open(os.path.join(root, '85-open-items.md'), 'w', encoding='utf-8', newline=NL).write(NL.join(oi) + NL)
print(dict(stats), 'nfr', len(nfrs), nfr_ok, nfr_dod, 'fw', len(fw), 'bw', len(bw), 'open', dict(counts))
